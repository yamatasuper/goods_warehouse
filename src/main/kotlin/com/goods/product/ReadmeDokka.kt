/**
 * Инструкция по запуску приложения.
 *
 * Это руководство поможет вам настроить и запустить приложение на локальной машине.
 *
 * ## Требования
 * - Java 17 или выше.
 * - Docker и Docker Compose.
 * - Gradle (или Gradle Wrapper, если он встроен в проект).
 *
 * ## Шаги запуска
 *
 * 1. **Клонирование репозитория**:
 *    ```bash
 *    git clone <URL_вашего_репозитория>
 *    cd <название_папки_проекта>
 *    ```
 *
 * 2. **Остановка текущих контейнеров и очистка данных**:
 *    Если ранее запускались контейнеры:
 *    ```bash
 *    sudo docker-compose down -v
 *    ```
 *    Убедитесь, что удалены старые данные базы данных:
 *    ```bash
 *    sudo rm -rf ./db-data
 *    ```
 *
 * 3. **Очистка проекта**:
 *    Запустите команду очистки:
 *    ```bash
 *    ./gradlew clean
 *    ```
 *    Если очистка завершилась ошибкой из-за занятых файлов, убедитесь, что файлы в директории `build` не используются. Если необходимо, удалите её вручную:
 *    ```bash
 *    sudo rm -rf build
 *    ```
 *
 * 4. **Сборка JAR-файла**:
 *    Используйте следующую команду для сборки:
 *    ```bash
 *    ./gradlew buildFatJar
 *    ```
 *    Убедитесь, что сборка завершилась успешно.
 *
 * 5. **Запуск Docker-контейнеров**:
 *    Для запуска контейнеров с приложением и базой данных выполните:
 *    ```bash
 *    sudo docker-compose up --build -d
 *    ```
 *    Убедитесь, что все контейнеры запущены:
 *    ```bash
 *    sudo docker ps
 *    ```
 *
 * 6. **Доступ к API**:
 *    Приложение будет доступно по адресу:
 *    ```
 *    http://localhost:8080
 *    ```
 *
 * 7. **Swagger UI** (если интегрирован):
 *    Доступно по адресу:
 *    ```
 *    http://localhost:8080/swagger
 *    ```
 *
 * ## Переменные окружения
 * Убедитесь, что настроены все переменные окружения:
 *
 * | Переменная         | Описание                       | Значение по умолчанию |
 * |--------------------|--------------------------------|-----------------------|
 * | `DATABASE_URL`     | URL базы данных               | `jdbc:postgresql://localhost:5432/mydb` |
 * | `DATABASE_USER`    | Пользователь базы данных      | `postgres`           |
 * | `DATABASE_PASSWORD`| Пароль базы данных            | `password`           |
 *
 * ## Тестирование
 * Для запуска тестов:
 * ```bash
 * ./gradlew test
 * ```
 *
 * ## Полезные команды
 * - Остановить и удалить все контейнеры и их данные:
 *   ```bash
 *   sudo docker-compose down -v
 *   ```
 * - Очистить проект и собрать заново:
 *   ```bash
 *   ./gradlew clean
 *   ./gradlew buildFatJar
 *   ```
 *
 * ## Открытие документации
 *
 * 1. Перейдите в директорию, содержащую сгенерированную документацию:
 *    ```bash
 *    cd build/dokka/html
 *    ```
 *
 * 2. Запустите локальный HTTP-сервер для просмотра документации:
 *    ```bash
 *    python3 -m http.server
 *    ```
 *
 * 3. Откройте веб-браузер и перейдите по следующему адресу:
 *    ```
 *    http://0.0.0.0:8000/index.html
 *    ```
 *
 */
