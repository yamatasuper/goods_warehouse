/**
 * Инструкция по запуску приложения.
 *
 * Это руководство поможет вам настроить и запустить приложение на локальной машине.
 *
 * ## Требования
 * - Java 17 или выше.
 * - Docker (если используется база данных, которая запускается через Docker).
 * - Gradle (или Gradle Wrapper, если он встроен в проект).
 *
 * ## Шаги запуска
 * 1. **Клонируйте репозиторий**:
 *    ```bash
 *    git clone <URL_вашего_репозитория>
 *    cd <название_папки_проекта>
 *    ```
 *
 * 2. **Запуск базы данных**:
 *    Если приложение использует Docker Compose для запуска базы данных:
 *    ```bash
 *    docker-compose up -d
 *    ```
 *
 * 3. **Сборка и запуск приложения**:
 *    Для запуска приложения используйте Gradle:
 *    ```bash
 *    ./gradlew bootRun
 *    ```
 *    Или, если у вас установлен Gradle:
 *    ```bash
 *    gradle bootRun
 *    ```
 *
 * 4. **Доступ к API**:
 *    Приложение будет доступно по адресу:
 *    ```
 *    http://localhost:8080
 *    ```
 *
 * 5. **Swagger UI** (если интегрирован):
 *    Доступно по адресу:
 *    ```
 *    http://localhost:8080/swagger-ui/index.html
 *    ```
 *
 * ## Переменные окружения
 * Убедитесь, что настроены все переменные окружения:
 *
 * | Переменная         | Описание                       | Значение по умолчанию |
 * |--------------------|--------------------------------|-----------------------|
 * | `DATABASE_URL`     | URL базы данных               | `jdbc:postgresql://localhost:5432/mydb` |
 * | `DATABASE_USER`    | Пользователь базы данных      | `postgres`           |
 * | `DATABASE_PASSWORD`| Пароль базы данных            | `password`           |
 *
 * ## Тестирование
 * Для запуска тестов:
 * ```bash
 * ./gradlew test
 * ```
 *
 * ## Сборка JAR
 * Для сборки JAR-файла используйте команду:
 * ```bash
 * ./gradlew build
 * ```
 *
 * JAR-файл будет находиться в директории `build/libs`.
 */
